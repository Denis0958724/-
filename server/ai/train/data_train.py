PREFIX = ['', '', '', 'Добрий день! ', 'Підкажіть, ', 'Питання: ', 'Привіт. ', 'Допоможіть, ', 'Здравствуйте, ', 'Терміново: ', 'Шановні, ']
SUFFIX = ['', '', '', ' Дякую.', ' Бюджет до 500 грн.', ' Потрібно сьогодні.', ' Заздалегідь дякую!', ' Хочу консультацію.', ' Спасибо.', ' Це терміново.']

def typo(s, rnd):
    if len(s) < 12: return s
    i = rnd.randrange(3, len(s) - 3)
    op = rnd.random()
    if op < 0.4: return s[:i] + s[i + 1:]
    if op < 0.7: return s[:i] + s[i + 1] + s[i] + s[i + 2:]
    return s[:i] + s[i] + s[i:]

def build(seed=7, copies=5):
    rnd = random.Random(seed)
    X, y = [], []
    for cat, items in HAND.items():
        for s in items:
            X.append(s); y.append(cat)
            for _ in range(copies):
                t = rnd.choice(PREFIX) + (s[0].lower() + s[1:] if rnd.random() < 0.5 else s) + rnd.choice(SUFFIX)
                if rnd.random() < 0.35: t = typo(t, rnd)
                if rnd.random() < 0.2: t = t.lower()
                if rnd.random() < 0.15: t = t.rstrip('?.!')
                X.append(t); y.append(cat)
    return X, y
